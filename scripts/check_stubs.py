"""Deterministic PEP 484 (.pyi) stub generator and drift checker for mailjet_rest.

Uses pure Python AST parsing (zero subprocess calls) so `--write` and `--check`
produce reproducible stubs across Python environments and CI runners.
"""

from __future__ import annotations

import argparse
import ast
import importlib.util
import sys
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parent.parent


def _default_package_dir() -> Path:
    repo_pkg = REPO_ROOT / "mailjet_rest"
    if repo_pkg.is_dir():
        return repo_pkg
    spec = importlib.util.find_spec("mailjet_rest")
    if spec is not None and spec.origin is not None:
        return Path(spec.origin).resolve().parent
    return repo_pkg


def _format_arg(arg: ast.arg, default: ast.expr | None) -> str:
    text = arg.arg
    if arg.annotation is not None:
        text = f"{text}: {ast.unparse(arg.annotation)}"
    if default is not None:
        text = f"{text} = ..."
    return text


def _is_async_generator(node: ast.AsyncFunctionDef) -> bool:
    stack: list[ast.AST] = list(node.body)
    while stack:
        stmt = stack.pop()
        if isinstance(stmt, (ast.Yield, ast.YieldFrom)):
            return True
        if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        stack.extend(ast.iter_child_nodes(stmt))
    return False


def _format_signature(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    args = node.args
    parts: list[str] = []

    positional = list(args.posonlyargs) + list(args.args)
    pos_defaults: list[ast.expr | None] = [None] * (len(positional) - len(args.defaults)) + list(args.defaults)

    for idx, (arg, default) in enumerate(zip(positional, pos_defaults, strict=True)):
        parts.append(_format_arg(arg, default))
        if args.posonlyargs and idx == len(args.posonlyargs) - 1:
            parts.append("/")

    if args.vararg is not None:
        parts.append(f"*{_format_arg(args.vararg, None)}")
    elif args.kwonlyargs:
        parts.append("*")

    for kwarg, kw_default in zip(args.kwonlyargs, args.kw_defaults, strict=True):
        parts.append(_format_arg(kwarg, kw_default))

    if args.kwarg is not None:
        parts.append(f"**{_format_arg(args.kwarg, None)}")

    ret = f" -> {ast.unparse(node.returns)}" if node.returns is not None else ""
    prefix = "async def" if isinstance(node, ast.AsyncFunctionDef) and not _is_async_generator(node) else "def"
    return f"{prefix} {node.name}({', '.join(parts)}){ret}: ..."


def _extract_route_names(routes_source: str) -> list[str]:
    tree = ast.parse(routes_source)
    for node in tree.body:
        targets: list[ast.expr] = []
        value: ast.expr | None = None
        if isinstance(node, ast.Assign):
            targets = node.targets
            value = node.value
        elif isinstance(node, ast.AnnAssign):
            targets = [node.target]
            value = node.value
        if any(isinstance(t, ast.Name) and t.id == "_ROUTE_MAP" for t in targets) and isinstance(value, ast.Dict):
            names = [k.value for k in value.keys if isinstance(k, ast.Constant) and isinstance(k.value, str)]
            return sorted(set(names))
    msg = "Unable to locate _ROUTE_MAP dictionary keys in mailjet_rest/routes.py"
    raise RuntimeError(msg)


def _find_class(tree: ast.Module, class_name: str) -> ast.ClassDef:
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == class_name:
            return node
    msg = f"Class {class_name!r} not found in AST"
    raise RuntimeError(msg)


def _find_top_function(tree: ast.Module, func_name: str) -> ast.FunctionDef:
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == func_name:
            return node
    msg = f"Function {func_name!r} not found in AST"
    raise RuntimeError(msg)


def _format_class_methods(cls_node: ast.ClassDef) -> list[str]:
    lines: list[str] = []
    for item in cls_node.body:
        if not isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        if item.name in {"__repr__", "__str__"}:
            continue
        lines.extend(f"    @{ast.unparse(dec)}" for dec in item.decorator_list)
        lines.append(f"    {_format_signature(item)}")
    return lines


def render_endpoint_stub(package_dir: Path) -> str:
    """Render deterministic stub content for mailjet_rest/endpoint.pyi.

    Returns:
        str: Formatted PEP 484 stub source for `mailjet_rest/endpoint.py`.
    """
    tree = ast.parse((package_dir / "endpoint.py").read_text(encoding="utf-8"))
    base_cls = _find_class(tree, "BaseEndpoint")
    ep_cls = _find_class(tree, "Endpoint")
    async_ep_cls = _find_class(tree, "AsyncEndpoint")

    lines = [
        "# Generated by scripts/check_stubs.py --write. Do not edit manually.",
        "from collections.abc import AsyncGenerator, Generator",
        "from typing import Any, ClassVar",
        "",
        "import httpx2",
        "import requests",
        "",
        "from mailjet_rest.client import AsyncClient, Client",
        "from mailjet_rest.types import (",
        "    HeadersMapping,",
        "    HttpMethod,",
        "    PayloadType,",
        "    QueryFilters,",
        "    RequestHeaders,",
        "    ResourceId,",
        "    TimeoutType,",
        ")",
        "",
        '__all__ = ["AsyncEndpoint", "BaseEndpoint", "Endpoint"]',
        "",
        "class BaseEndpoint:",
        "    MAX_LIMIT: ClassVar[int]",
        "    client: Any",
        "    name: str",
        "    _name_lower: str",
        "    _resource_lower: str",
        "    _action_parts: list[str]",
    ]
    lines.extend(_format_class_methods(base_cls))
    lines.extend(["", "class Endpoint(BaseEndpoint):", "    client: Client"])
    lines.extend(_format_class_methods(ep_cls))
    lines.extend(["", "class AsyncEndpoint(BaseEndpoint):", "    client: AsyncClient"])
    lines.extend(_format_class_methods(async_ep_cls))
    lines.append("")
    return "\n".join(lines)


def _format_route_properties(routes: list[str], reserved_attrs: set[str], endpoint_cls_name: str) -> list[str]:
    lines: list[str] = []
    for route in routes:
        if route not in reserved_attrs and route.isidentifier():
            lines.extend(("    @property", f"    def {route}(self) -> {endpoint_cls_name}: ..."))
    return lines


def render_client_stub(package_dir: Path) -> str:
    """Render deterministic stub content for mailjet_rest/client.pyi.

    Returns:
        str: Formatted PEP 484 stub source for `mailjet_rest/client.py`.
    """
    tree = ast.parse((package_dir / "client.py").read_text(encoding="utf-8"))
    routes = _extract_route_names((package_dir / "routes.py").read_text(encoding="utf-8"))

    base_client_cls = _find_class(tree, "BaseClient")
    client_cls = _find_class(tree, "Client")
    async_client_cls = _find_class(tree, "AsyncClient")
    parse_response_fn = _find_top_function(tree, "parse_response")
    logging_handler_fn = _find_top_function(tree, "logging_handler")

    lines = [
        "# Generated by scripts/check_stubs.py --write. Do not edit manually.",
        "import logging",
        "import sys",
        "import threading",
        "from collections.abc import Mapping",
        "from types import TracebackType",
        "from typing import Any, ClassVar, NoReturn, TypeVar",
        "",
        "import httpx2",
        "import requests",
        "",
        "from mailjet_rest.config import Config as Config",
        "from mailjet_rest.endpoint import AsyncEndpoint as AsyncEndpoint, BaseEndpoint as BaseEndpoint, Endpoint as Endpoint",
        "from mailjet_rest.errors import (",
        "    ActionDeniedError as ActionDeniedError,",
        "    ApiError as ApiError,",
        "    ApiRateLimitError as ApiRateLimitError,",
        "    AuthorizationError as AuthorizationError,",
        "    CriticalApiError as CriticalApiError,",
        "    DoesNotExistError as DoesNotExistError,",
        "    MailjetApiError as MailjetApiError,",
        "    MailjetAuthError as MailjetAuthError,",
        "    TimeoutError as TimeoutError,",
        "    ValidationError as ValidationError,",
        ")",
        "from mailjet_rest.types import (",
        "    AuthCredentials,",
        "    CertConfig,",
        "    HeadersMapping,",
        "    HttpMethod,",
        "    PayloadType,",
        "    QueryFilters,",
        "    RequestHeaders,",
        "    TimeoutType,",
        ")",
        "from mailjet_rest.utils.guardrails import SecretAuth",
        "from mailjet_rest.utils.retry import JitterRetry as JitterRetry",
        "",
        "if sys.version_info >= (3, 11):",
        "    from typing import Self",
        "else:",
        "    from typing_extensions import Self",
        "",
        "__all__ = [",
        '    "ActionDeniedError",',
        '    "ApiError",',
        '    "ApiRateLimitError",',
        '    "AsyncClient",',
        '    "AsyncEndpoint",',
        '    "AuthorizationError",',
        '    "BaseClient",',
        '    "Client",',
        '    "Config",',
        '    "CriticalApiError",',
        '    "DoesNotExistError",',
        '    "Endpoint",',
        '    "JitterRetry",',
        '    "MailjetApiError",',
        '    "MailjetAuthError",',
        '    "TimeoutError",',
        '    "ValidationError",',
        '    "logging_handler",',
        '    "parse_response",',
        "]",
        "",
        '_EndpointT = TypeVar("_EndpointT", bound=BaseEndpoint)',
        "_httpx2: Any",
        "logger: logging.Logger",
        "",
        "class BaseClient:",
        "    _MAX_ERROR_DETAIL_CHARS: ClassVar[int]",
        "    _MAX_ERROR_LOG_CHARS: ClassVar[int]",
        "    _MUTATING_METHODS: ClassVar[frozenset[str]]",
        "    _RETRY_STRATEGY: ClassVar[JitterRetry]",
        "    _closed: bool",
        "    _endpoint_cache: Any",
        "    _lock: threading.RLock",
        "    _session: Any",
        "    auth: str | SecretAuth | None",
        "    config: Config",
    ]
    lines.extend(_format_class_methods(base_client_cls))

    reserved_attrs = {
        "__getattr__",
        "aclose",
        "api_call",
        "auth",
        "available_endpoints",
        "close",
        "config",
        "ping",
        "session",
    }
    lines.extend(
        [
            "",
            "class Client(BaseClient):",
            "    _endpoint_cache: dict[str, Endpoint]",
            "    _session: requests.Session | None",
        ]
    )
    lines.extend(_format_class_methods(client_cls))
    lines.extend(_format_route_properties(routes, reserved_attrs, "Endpoint"))

    lines.extend(
        [
            "",
            "class AsyncClient(BaseClient):",
            "    _custom_transport: httpx2.AsyncBaseTransport | None",
            "    _endpoint_cache: dict[str, AsyncEndpoint]",
            "    _session: httpx2.AsyncClient | None",
        ]
    )
    lines.extend(_format_class_methods(async_client_cls))
    lines.extend(_format_route_properties(routes, reserved_attrs, "AsyncEndpoint"))

    lines.extend(
        [
            "",
            _format_signature(parse_response_fn),
            _format_signature(logging_handler_fn),
            "",
        ]
    )
    return "\n".join(lines)


def expected_stubs(package_dir: Path) -> dict[Path, str]:
    """Compute expected stub file paths and deterministic contents for a package directory.

    Returns:
        dict[Path, str]: Mapping from stub `.pyi` path to expected deterministic text.
    """
    resolved_dir = package_dir.resolve()
    return {
        resolved_dir / "endpoint.pyi": render_endpoint_stub(resolved_dir),
        resolved_dir / "client.pyi": render_client_stub(resolved_dir),
    }


def check_or_write_stubs(package_dir: Path, *, write: bool) -> list[Path]:
    """Check stub files for drift or overwrite them when `write=True`.

    Returns:
        list[Path]: Paths that differed from deterministic output (or were updated).
    """
    drifted: list[Path] = []
    for stub_path, rendered in expected_stubs(package_dir).items():
        current = stub_path.read_text(encoding="utf-8") if stub_path.exists() else None
        if current != rendered:
            drifted.append(stub_path)
            if write:
                stub_path.write_text(rendered, encoding="utf-8")
    return drifted


def main(argv: list[str] | None = None) -> int:
    """CLI entry point supporting `--write` and `--check`.

    Returns:
        int: Process exit code (`0` when synchronized, `1` when drift is detected).
    """
    parser = argparse.ArgumentParser(description="Generate or verify tracked .pyi stubs for mailjet_rest.")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="Write deterministic .pyi stub files.")
    mode.add_argument("--check", action="store_true", help="Fail if any .pyi stub drifted from source AST.")
    parser.add_argument(
        "--package-dir",
        type=Path,
        default=_default_package_dir(),
        help="Path to the mailjet_rest package directory.",
    )
    args = parser.parse_args(argv)

    package_dir = args.package_dir.resolve()
    drifted = check_or_write_stubs(package_dir, write=bool(args.write))

    if args.check:
        if drifted:
            for path in drifted:
                print(f"Stub drift detected: {path}")
            return 1
        print(f"Stubs up to date ({len(expected_stubs(package_dir))} files verified).")
        return 0

    print(f"Stubs synchronized ({len(drifted)} updated).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
